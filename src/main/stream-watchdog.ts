/**
 * 流式请求的**停顿**看门狗。
 *
 * ## 这里修的是什么
 *
 * 原来 `ipc/ai.ts` 里是这么写的：每次 HTTP 往返（工具循环里的一轮）
 * 起一个 `setTimeout(120_000)`，到点就 abort 并报「请求超时（120s）」。
 *
 * 计时器起于请求发出、清于这一轮结束（`settle()`），所以它的覆盖范围是
 * **一次往返的全过程**：建连 + 等首字 + 模型输出（正文 / 思维链 /
 * 工具调用参数）。用户问「正常不是一轮过后就重新计算时间了？」——
 * 确实每轮都重置，问题不在重置，而在于**每轮给的是「总时长上限」，
 * 不是「空闲上限」**：只要这一轮墙钟超过 120 秒就砍，与期间有没有在吐字无关。
 *
 * 于是出现两个现象：
 *
 *   1. **「AI 明明在输出，却因为 120s 的限制结束了」**。
 *      模型连续输出超过 2 分钟（长代码、长解释、推理模型的长思维链），
 *      第 120 秒必然被 abort，哪怕那一刻分片还在源源不断地到。
 *   2. **「最后改代码的时候因为超时被中断了」**。
 *      要调 editFile 的那一轮，模型得先把思维链与正文吐完，再分片吐出
 *      工具调用参数 —— 推理模型「想得久」很常见，整个往返超过 120 秒时，
 *      参数还没吐完就被掐断。表现就是「正要改代码，突然超时结束了」。
 *      （工具**执行**本身不在计时范围内：那时这一轮已经 settle、表已撤。）
 *
 * 附带第三个问题：**报错文案指向网络**，而真实原因可能是「这个模型就是慢」，
 * 用户按提示去查中转站，白折腾。
 *
 * ## 现在怎么算
 *
 * 改成**停顿**（stall）看门狗：只要连接还在送东西，就一直不算超时。
 * 计时器在**每一片到达的数据**上重置 —— 正文分片、思维链分片、
 * 工具调用参数分片，连中转站发的保活注释（SSE 的 `: keep-alive`）也算：
 * 那同样证明「这条连接还活着，不是卡死」。
 *
 * 所以那个疑问现在有了确定的答案：是每轮重置，而且比一轮更细 ——
 * 轮内每来一片内容都重新算。工具执行期间则完全不在计时范围内
 * （一轮结束表就撤了，下一个请求才重新起表）。
 *
 * ## 为什么不干脆去掉超时
 *
 * 因为「上游半死不活」是真实存在的：连接建立了、一个字节都不再发，
 * 而 TCP 也一直不报错。没有看门狗的话界面就永远转圈，学生只能强杀进程。
 * 停顿阈值要防的是这种，不是「模型输出得慢」。
 *
 * 所以阈值给得比原来宽得多：默认 5 分钟没有任何数据才算卡死。
 * 正常情况下这个数永远碰不到（分片是每秒几十个地到）。
 *
 * ## 为什么单独一个文件
 *
 * 这两个阈值与文案构成「超时到底怎么算」的全部规则。
 * 它们原来散在 `ipc/ai.ts` 的请求函数里，与 HTTP、SSE 解析混在一起 ——
 * 想确认「计时器覆盖哪一段」得把整个函数读完。
 * 抽出来之后 `scripts/check-idle-timeout.mjs` 可以直接对着它跑断言，
 * 不必启动 Electron。
 */

/**
 * 多久没有收到**任何数据**就判定为卡死（毫秒）。
 *
 * 5 分钟的依据：
 *   - 正常流式输出：每秒几十个分片，这个数永远碰不到
 *   - 首字节延迟（TTFT）：大上下文 + 慢模型时，中转站可能几十秒才吐第一个字。
 *     ⚠️ 这一条正是它不能设小的原因 —— HTTP 响应头通常**要等第一个 token
 *     生成出来才发**，所以「连接阶段」和「等首字」在时间上分不开，
 *     30 秒那种值会把大上下文的正常请求误杀
 *   - 上游排队 / 限流：实测最坏几十秒内会开始吐字
 *   - 推理模型「想很久才开始答」：DeepSeek-R1 这类可能一两分钟不出正文，
 *     但思维链也在流里（reasoning 分片同样重置计时器），留足余量
 *   - 工具执行：最长 5 分钟（RUN_TIMEOUT_MAX_MS），且工具期间不计时
 *     （一轮已经结束、看门狗已撤），所以不冲突
 */
export const STREAM_STALL_TIMEOUT_MS = 5 * 60 * 1000

/**
 * 单轮（一次 HTTP 往返）的**硬上限**，兜住「连接一直活着但永远不出内容」。
 *
 * 停顿看门狗有个天然的漏洞：中转站如果一直发保活注释、模型却永远不答，
 * 计时器会被无限重置，界面就永远转圈。这一条是那个漏洞的兜底。
 *
 * 15 分钟的依据：单轮输出受 max_tokens 约束（常见 4k~8k），
 * 按每秒 30 token 算，8k token 也就 4.5 分钟。15 分钟已经是很宽的余量，
 * 真到这一步基本可以断定上游出问题了。
 *
 * 注意它**不覆盖工具执行时间** —— 一轮结束（模型给出 tool_calls）时
 * 计时器就撤了，工具跑完开下一轮才重新起表。
 */
export const STREAM_ROUND_MAX_MS = 15 * 60 * 1000

/**
 * 超时文案。
 *
 * 分两种写法，因为两种情况的处置完全不同：
 *   - 停顿超时 → 请求已经成功过（前面有内容进来了），
 *     多半是上游卡住或这个模型太慢，重发一次通常就好
 *   - 单轮硬上限 → 连接一直活着但一直不给内容，
 *     这是中转站的问题，换模型或换站比重试有用
 *
 * 原文案一律写「请检查网络或中转站状态」，对着这两种情况都是误导 ——
 * 用户会去查自己的网络，而问题不在那里。
 */
export function stallTimeoutMessage(kind: 'stall' | 'ceiling', timeoutMs: number): string {
  const seconds = Math.round(timeoutMs / 1000)
  const minutes = Math.round(timeoutMs / 60_000)
  if (kind === 'ceiling') {
    return (
      `本轮请求已持续 ${minutes} 分钟仍未结束，已中断。\n\n` +
      '已经生成的内容都保留在上面了。这种情况通常是中转站一直挂着连接却不给内容，\n' +
      '换一个模型或换一个中转站比直接重试更有用。'
    )
  }
  return (
    `请求中断：已经 ${seconds}s 没有收到任何新内容，判定为上游卡死。\n\n` +
    '已经生成的内容都保留在上面了。可以直接再发一次（或点这条消息的「重试」）——\n' +
    '如果每次都卡在差不多的地方，多半是这个模型 / 中转站本身不稳定，换一个模型试试。'
  )
}
