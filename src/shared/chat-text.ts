/**
 * 聊天气泡里的文本清理：把**无意义的换行**去掉。
 *
 * ## 为什么需要它
 *
 * 一次带工具的回答是**好几轮**拼起来的：模型先说一句「我先看一下这个文件」，
 * 调工具，拿到结果再说下一段……每一轮的正文都被追加进同一个气泡。
 *
 * 问题在于模型习惯在每段前后各带一两个换行：
 *
 *     第 1 轮 content = "我先读一下这个文件。\n\n"
 *     第 2 轮 content = "\n接下来改第 12 行。\n\n"
 *     第 3 轮 content = "\n\n改好了。"
 *
 * 拼起来就是「我先读一下这个文件。\n\n\n接下来改第 12 行。\n\n\n\n改好了。」——
 * 气泡里每执行一次工具就多出一片空白，五次工具调用之后正文被推得老远。
 * 学生看到的是「AI 每查看一个文件，气泡就换一行」，而答案不知道跑哪去了。
 *
 * ## 清理到什么程度
 *
 *   1. 统一换行符（`\r\n` / `\r` → `\n`）：Windows 上模型有时会带 CRLF
 *   2. 去掉每行**行尾**的空格与制表符（不可见，但会让复制出来的代码带脏尾）
 *   3. **3 个以上连续换行压成 2 个** —— 即「最多留一个空行」。
 *      刻意不是全删：模型用空行分段是**有意义**的排版，
 *      压成一段反而更难读。要治的是「多了两三个空行」这种。
 *   4. 去掉开头与结尾的空行。气泡有自己的内边距，
 *      正文再顶一个空行只是白白把气泡撑高。
 *
 * ## 行首缩进一律不动
 *
 * 只动行尾。行首的空格是代码缩进，动了就把 AI 给的代码改坏了 ——
 * 而这个函数的结果会**存进会话记录**，改坏了会一直留在历史里。
 *
 * ## 流式期间也能用
 *
 * 每次渲染都对当前文本跑一遍，不做增量状态。
 * 尾巴上「刚到的几个换行」会被临时压掉，下一段正文到了又正常显示 ——
 * 最坏是一瞬间的跳动，比攒着不显示好。
 */

/** 连续换行的上限：3 个以上压成 2 个（= 最多一个空行） */
const MAX_BLANK_LINES = 2

/**
 * 清理一段聊天正文。
 *
 * 纯函数、幂等：`normalizeChatText(normalizeChatText(x)) === normalizeChatText(x)`。
 * 幂等很重要 —— 显示路径与落盘路径都会调它，一段文本可能被处理两次
 * （先显示、再存，或者存过之后再显示一次），结果必须一样。
 */
export function normalizeChatText(raw: string): string {
  if (!raw) return ''
  return raw
    // 1. 统一换行符。CRLF 不统一的话，下面按 \n 数的连续换行会数错
    .replace(/\r\n?/g, '\n')
    // 2. 行尾空白（不动行首：那是代码缩进）
    .replace(/[ \t]+$/gm, '')
    // 3. 连续空行收敛
    .replace(/\n{3,}/g, '\n'.repeat(MAX_BLANK_LINES))
    // 4. 首尾空行
    .replace(/^\n+/, '')
    .replace(/\n+$/, '')
}

/**
 * 这段文本是不是「只剩空白」。
 *
 * 用来识别「模型这一轮只吐了几个换行就去调工具了」——
 * 这种内容不该在气泡里占位置，但也不该当成「已经答了」。
 */
export function isBlankChatText(raw: string): boolean {
  return raw.trim() === ''
}
