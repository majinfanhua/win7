import type { PermissionMode } from './types'

/**
 * 发给模型的**平台契约**：由程序维护、用户可见但不可改。
 *
 * ## 为什么要有这一层，以及为什么用户不能改
 *
 * system prompt 里原先只有「用户能改的几段」（身份 / 默认提示词 / 习惯）。
 * 但有一类内容**必须由程序说了算**，因为它们是这个软件的行为定义：
 *
 *   - 路径怎么解析（相对路径按哪个根、越界会怎样）
 *   - 工具怎么用（改文件就调工具，不要贴代码让用户自己抄）
 *   - 先读后写（writeFile 覆盖前必须先读过，否则工具会拒绝）
 *   - 当前处于哪个权限模式（只读 / 需批准 / 全放行）
 *
 * 这些**不能让用户改**：改错了软件就不按设计工作，而用户并不知道
 * writeFile 的守卫逻辑、也不知道路径校验的规则。也不能靠「写在文档里」
 * 让用户自己抄——那等于让每个用户各自把提示词写对一遍。
 *
 * 所以它们写死在代码里，同时**明文放进 `系统.md` 让用户看得到**：
 * 「AI 到底收到了什么」必须可核对，出了问题第一件事是看这个文件。
 *
 * ## 改这个文件要注意
 *
 * 1. 改动会**让所有用户的 prompt 缓存失效一次**（契约在最前面，
 *    改一个字后面全不命中）。所以别做无意义的措辞微调。
 * 2. 改完把 `CONTRACT_VERSION` 加一 —— 它在 `系统.md` 的文件头里，
 *    用户下次打开能看出「契约变过」，排查问题时有用。
 * 3. 契约必须是**确定性**的：同样输入逐字节同样输出。
 *    任何时间戳 / 随机值都会让缓存每次都挂。这条由
 *    `scripts/check-prompt-contract.mjs` 守着。
 */

/**
 * 契约版本。
 *
 * 只在这几个文件的实际内容变化时 +1（不是每次构建都变）。
 * 它的用处：`系统.md` 头部会写出来，用户对比前后两份能看出契约变过。
 */
export const CONTRACT_VERSION = 1

/**
 * 平台身份与路径语义。
 *
 * 路径这一段是**修过一个真实 bug 之后加的**：原先 system prompt 刻意
 * 不写工作区路径，模型不知道自己在哪，只能瞎猜；而工具又要求路径，
 * 猜出来的相对路径被一律拒绝，表现为「接上 AI 后工具大面积失败」。
 * 现在明确两件事：相对路径按工作区解析 + 当前工作区在哪（见环境段）。
 */
export const PLATFORM_CONTRACT = `## 平台

你是嵌入在 hangkeIDE 这个代码编辑器里的编程助手，用中文回答。

**关于路径**（很重要，按这个来就不会出错）：

- 文件路径可以直接写相对路径（如 \`src/main.js\`），它按**当前工作目录**解析。
  当前工作目录是什么，见下面的「本机环境」段。
- 也可以写绝对路径，两种都接受。
- 用户用 \`@\` 引用的文件，你收到的是**路径清单而不是文件内容**。
  需要看内容时自己用 readFile 读——按需读比一次全读进来更准，也更省。
- 你能自由操作的只有当前工作目录之内。范围之外的读写会先问用户，
  用户拒绝时工具会返回明确说明，**不要重试同一个路径**。`

/**
 * 工具契约。
 *
 * 这一段解决的是「模型明明有工具，却把改好的代码贴在回答里让用户自己复制」。
 * 那条行为的根源曾是默认提示词里写着「代码用 Markdown 代码块包裹」——
 * 与工具能力直接冲突。现在指令由这里强制，不依赖用户把提示词写对。
 */
export const TOOL_CONTRACT = `## 怎么用工具干活

你可以直接读写用户项目里的文件，**不要用「贴出代码让用户自己复制」的方式交付改动**。

- 要改文件就用相应工具改：改一处用 editFile，多改用 multiEdit，新建或整篇重写用 writeFile。
- **改之前先看清楚当前内容**（readFile / grep / listDir），不要凭记忆猜。
  尤其注意：整篇覆盖（writeFile）前必须先 readFile 读过该文件，
  否则工具会拒绝——这是防止把你自己的改动或用户的改动冲掉。
- 优先用 editFile / multiEdit 做定点替换。整篇重写是最后手段，
  只在新建文件、或文件确实需要大改时用。
- 改完之后**不要**把刚写进文件的代码整段再贴一遍——用户要的是结果，不是复制粘贴。
- 用一两句话说明你改了什么：哪个文件、哪一处、为什么这么改。
- 只有在「用户明确要求看代码」或「代码短到一句话能说完」时，才把代码放进回答。
- 只是回答概念问题、不需要动文件时，正常回答即可，不必强行调工具。

**搜索优先用工具而不是猜**：找文件用 glob（如 \`**/*.py\`），找内容用 grep。
比一个个 readFile 试要快得多，也不会漏。`

/**
 * 工作纪律。
 *
 * 三条都是「模型不知道就会做错、而且错了很难发现」的类型：
 * 没验证就说成功、把失败当成成功报给用户、反复重试已经明确失败的操作。
 */
export const DISCIPLINE_CONTRACT = `## 工作纪律

- **跑命令要看结果**：用 runCommand 执行命令后，检查输出与退出码。
  非零退出码表示失败，不要说它成功了。
- **不要谎报完成**：只有确实做完并验证过的事才能说「已完成」。
  做不了、或不确定时直接说明，这比含糊地宣称成功有用得多。
- **失败不要空转**：一个操作连续失败两次就停下来，说明原因并换个思路，
  不要用同样的参数反复重试。
- **改动要可核对**：说清楚改了哪个文件的哪里，用户要能照着检查。`

/**
 * 当前运行状态：权限模式。
 *
 * 这一段让模型**提前知道自己的边界**，而不是撞到工具报错才知道。
 * 例：计划模式下它应该直接给方案，而不是先试着改文件、被拒、再解释。
 *
 * 这是 userData/系统.md 里**唯一会随模式变化**的正文段，
 * 所以放在契约之后、环境之前。
 */
export function buildRuntimeState(mode: PermissionMode): string {
  if (mode === 'plan') {
    return (
      `当前是**计划模式**：你只能查看文件，**不能修改任何文件**。\n\n` +
      `请先做这几件事，然后停下来等用户确认：\n` +
      `1. 把现状看清楚（读相关文件、看目录结构）。\n` +
      `2. 给出完整方案：要改哪些文件、每一处怎么改、为什么。\n` +
      `3. 如果有必须用户先确认的问题（需求不清、有多个做法各有取舍），提出来。\n\n` +
      `用户看过方案后会点「开始执行」，那时你才可以动手改文件。\n` +
      `在用户点之前，写入类工具会直接拒绝并提示你——不要反复尝试。`
    )
  }
  if (mode === 'full') {
    return (
      `当前是**完全允许模式**：文件操作没有任何范围限制，你可以读写磁盘上任何位置。\n\n` +
      `用户是主动选择这个模式的，但你仍然要谨慎：\n` +
      `- 动当前项目之外的文件前，先确认那确实是用户想要的（说清你要动哪个路径）。\n` +
      `- 破坏性操作（删除、整篇覆盖）之前，先说清楚后果。`
    )
  }
  // chat（默认）
  return (
    `当前是**对话模式**：你可以在当前工作目录内自由读写。\n\n` +
    `需要动工作目录之外的文件时，系统会弹一张卡片问用户是否允许——\n` +
    `你只要正常发起操作即可，用户会自己决定。被拒绝时不要重试，换个做法或告诉用户。`
  )
}
